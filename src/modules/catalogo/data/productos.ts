import type { Producto } from '../types'

const GRANDES = import.meta.glob<string>(['../assets/productos/*.webp', '!../assets/productos/*-400.webp'], {
  eager: true,
  import: 'default',
})
const CHICAS = import.meta.glob<string>('../assets/productos/*-400.webp', { eager: true, import: 'default' })

/** Foto de la prenda (ancho real en px) con su versión de 400 px para tarjetas angostas. */
function foto(archivo: string, ancho: number, alt: string): Producto['imagen'] {
  const src = GRANDES[`../assets/productos/${archivo}.webp`]
  const chica = CHICAS[`../assets/productos/${archivo}-400.webp`]
  if (!src || !chica) throw new Error(`Falta la foto del producto «${archivo}»`)
  return { src, srcset: `${chica} 400w, ${src} ${ancho}w`, alt }
}

